USE DATABASE TFS_NEXT_MOVE;
USE SCHEMA CORE;

CREATE TABLE IF NOT EXISTS VEHICLE_TELEMETRY (
  VEHICLE_ID VARCHAR PRIMARY KEY, CAPTURED_AT TIMESTAMP_TZ, ODOMETER_MILES INTEGER,
  TIRE_PRESSURE_PSI VARIANT, BATTERY_TYPE VARCHAR, BATTERY_HEALTH_PERCENT NUMBER(5,2),
  BATTERY_VOLTAGE NUMBER(5,2), STATE_OF_CHARGE_PERCENT NUMBER(5,2),
  ESTIMATED_RANGE_MILES INTEGER, EQUIVALENT_FULL_CYCLES INTEGER,
  SIMULATED BOOLEAN DEFAULT TRUE
);

MERGE INTO VEHICLE_TELEMETRY target
USING (
  SELECT column1 VEHICLE_ID, column2::TIMESTAMP_TZ CAPTURED_AT, column3 ODOMETER_MILES,
         PARSE_JSON(column4) TIRE_PRESSURE_PSI, column5 BATTERY_TYPE,
         column6 BATTERY_HEALTH_PERCENT, column7 BATTERY_VOLTAGE,
         column8 STATE_OF_CHARGE_PERCENT, column9 ESTIMATED_RANGE_MILES,
         column10 EQUIVALENT_FULL_CYCLES
  FROM VALUES
    ('guardian-camry-alex','2026-10-25 09:15:00 -0500',78000,'{"front_left":34,"front_right":34,"rear_left":33,"rear_right":33}','12V',82,12.5,NULL,NULL,NULL),
    ('guardian-camry-covered','2026-10-25 09:17:00 -0500',69000,'{"front_left":35,"front_right":35,"rear_left":34,"rear_right":34}','12V',91,12.7,NULL,NULL,NULL),
    ('guardian-camry-limited','2026-10-25 09:20:00 -0500',92000,'{"front_left":31,"front_right":33,"rear_left":32,"rear_right":32}','12V',68,12.2,NULL,NULL,NULL)
) source ON target.VEHICLE_ID = source.VEHICLE_ID
WHEN MATCHED THEN UPDATE SET
  CAPTURED_AT=source.CAPTURED_AT, ODOMETER_MILES=source.ODOMETER_MILES,
  TIRE_PRESSURE_PSI=source.TIRE_PRESSURE_PSI, BATTERY_TYPE=source.BATTERY_TYPE,
  BATTERY_HEALTH_PERCENT=source.BATTERY_HEALTH_PERCENT,
  BATTERY_VOLTAGE=source.BATTERY_VOLTAGE,
  STATE_OF_CHARGE_PERCENT=source.STATE_OF_CHARGE_PERCENT,
  ESTIMATED_RANGE_MILES=source.ESTIMATED_RANGE_MILES,
  EQUIVALENT_FULL_CYCLES=source.EQUIVALENT_FULL_CYCLES, SIMULATED=TRUE
WHEN NOT MATCHED THEN INSERT (
  VEHICLE_ID,CAPTURED_AT,ODOMETER_MILES,TIRE_PRESSURE_PSI,BATTERY_TYPE,
  BATTERY_HEALTH_PERCENT,BATTERY_VOLTAGE,STATE_OF_CHARGE_PERCENT,
  ESTIMATED_RANGE_MILES,EQUIVALENT_FULL_CYCLES,SIMULATED
) VALUES (
  source.VEHICLE_ID,source.CAPTURED_AT,source.ODOMETER_MILES,source.TIRE_PRESSURE_PSI,
  source.BATTERY_TYPE,source.BATTERY_HEALTH_PERCENT,source.BATTERY_VOLTAGE,
  source.STATE_OF_CHARGE_PERCENT,source.ESTIMATED_RANGE_MILES,
  source.EQUIVALENT_FULL_CYCLES,TRUE
);

GRANT SELECT ON TABLE TFS_NEXT_MOVE.CORE.VEHICLE_TELEMETRY TO ROLE NEXTMOVE_APP_ROLE;
