CREATE DATABASE IF NOT EXISTS TFS_NEXT_MOVE;
CREATE SCHEMA IF NOT EXISTS TFS_NEXT_MOVE.CORE;
USE DATABASE TFS_NEXT_MOVE;
USE SCHEMA CORE;

CREATE TABLE IF NOT EXISTS CUSTOMER (
  PROFILE_ID VARCHAR PRIMARY KEY, REGION VARCHAR, BUDGET_MONTHLY NUMBER(12,2),
  CASH_RESERVE NUMBER(12,2), SIMULATED BOOLEAN DEFAULT TRUE
);
ALTER TABLE CUSTOMER ADD COLUMN IF NOT EXISTS FIRST_NAME VARCHAR;
ALTER TABLE CUSTOMER ADD COLUMN IF NOT EXISTS INITIALS VARCHAR;
ALTER TABLE CUSTOMER ADD COLUMN IF NOT EXISTS PROFILE_LABEL VARCHAR;
ALTER TABLE CUSTOMER ADD COLUMN IF NOT EXISTS SERVICE_COVERAGE_LIMIT NUMBER(12,2);
ALTER TABLE CUSTOMER ADD COLUMN IF NOT EXISTS PROTECTED_CASH_RESERVE NUMBER(12,2);
CREATE TABLE IF NOT EXISTS VEHICLE (
  VEHICLE_ID VARCHAR PRIMARY KEY, PROFILE_ID VARCHAR, MODEL_YEAR INTEGER,
  MAKE VARCHAR, MODEL VARCHAR, TRIM VARCHAR, CURRENT_MILEAGE INTEGER
);
CREATE TABLE IF NOT EXISTS CONTRACT (
  CONTRACT_ID VARCHAR PRIMARY KEY, PROFILE_ID VARCHAR, VEHICLE_ID VARCHAR,
  CONTRACT_TYPE VARCHAR, MONTHLY_PAYMENT NUMBER(12,2), MONTHS_REMAINING INTEGER,
  MATURITY_DATE DATE, BUYOUT_AMOUNT NUMBER(12,2), PAYOFF_AMOUNT NUMBER(12,2),
  APR NUMBER(9,6), REMAINING_TERM_MONTHS INTEGER, MILEAGE_ALLOWANCE INTEGER,
  EXCESS_MILE_RATE NUMBER(9,2), DISPOSITION_FEE NUMBER(12,2), CONTRACT_VERSION VARCHAR
);
CREATE TABLE IF NOT EXISTS SERVICE_HISTORY (
  SERVICE_ID VARCHAR PRIMARY KEY, VEHICLE_ID VARCHAR, SERVICE_DATE DATE,
  MILEAGE INTEGER, SERVICE_TYPE VARCHAR, COST NUMBER(12,2), NOTES VARCHAR
);
CREATE TABLE IF NOT EXISTS VEHICLE_TELEMETRY (
  VEHICLE_ID VARCHAR PRIMARY KEY, CAPTURED_AT TIMESTAMP_TZ, ODOMETER_MILES INTEGER,
  TIRE_PRESSURE_PSI VARIANT, BATTERY_TYPE VARCHAR, BATTERY_HEALTH_PERCENT NUMBER(5,2),
  BATTERY_VOLTAGE NUMBER(5,2), STATE_OF_CHARGE_PERCENT NUMBER(5,2),
  ESTIMATED_RANGE_MILES INTEGER, EQUIVALENT_FULL_CYCLES INTEGER,
  SIMULATED BOOLEAN DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS MOBILITY_PREFERENCE (
  PROFILE_ID VARCHAR, PREFERENCE_VERSION VARCHAR, EXPECTED_MONTHLY_MILES INTEGER,
  HARD_CONSTRAINTS VARIANT, OPTIONAL_PREFERENCES VARIANT,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS EVIDENCE (
  EVIDENCE_ID VARCHAR PRIMARY KEY, SOURCE_TYPE VARCHAR, SOURCE_URL VARCHAR,
  RETRIEVED_AT TIMESTAMP_TZ, QUERY_PARAMETERS VARIANT, NORMALIZED_FACTS VARIANT,
  RAW_RESPONSE VARIANT, STATUS VARCHAR
);
CREATE TABLE IF NOT EXISTS SCENARIO_RUN (
  RUN_ID VARCHAR PRIMARY KEY, PROFILE_ID VARCHAR, DECISION_TYPE VARCHAR,
  HORIZON_MONTHS INTEGER, CALCULATOR_VERSION VARCHAR, INPUTS VARIANT, OPTIONS VARIANT,
  ASSUMPTIONS VARIANT, UNKNOWNS VARIANT, EVIDENCE_IDS ARRAY,
  RECOMMENDED_OPTION_ID VARCHAR, CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS ACTION_EVENT (
  ACTION_EVENT_ID VARCHAR PRIMARY KEY, RUN_ID VARCHAR, PROFILE_ID VARCHAR,
  ACTION_TYPE VARCHAR, ACTION_STATUS VARCHAR, PAYLOAD VARIANT,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

